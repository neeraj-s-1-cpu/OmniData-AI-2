export function resolveLanguageCode(raw?: string | null): ResolvedLanguageCode {
  const val = String(raw || "auto").trim().toLowerCase();
  if (val && val !== "auto") {
    const found = SUPPORTED_LANGUAGES.find((l) => l.code === val);
    if (found && found.code !== "auto") {
      return found.code;
    }
  }
  if (typeof navigator !== "undefined") {
    const navLang = (navigator.language || "en").toLowerCase();
    const prefix = navLang.split("-")[0];
    const match = SUPPORTED_LANGUAGES.find(
      (l) => l.code !== "auto" && (l.code === navLang || l.code === prefix)
    );
    if (match && match.code !== "auto") {
      return match.code;
    }
  }
  return "en";
}

export function getSpeechRecognitionLocale(raw?: string | null): string {
  const resolved = resolveLanguageCode(raw);
  const opt = SUPPORTED_LANGUAGES.find((l) => l.code === resolved);
  return opt?.speechLocale || "en-IN";
}

export function translateKey(
  lang: ResolvedLanguageCode,
  key: TranslationKey
): string {
  return TRANSLATIONS[lang]?.[key] || TRANSLATION_KEYS[key];
}

interface LanguageContextValue {
  languageSetting: string;
  lang: ResolvedLanguageCode;
  speechLocale: string;
  isRtl: boolean;
  t: (key: TranslationKey) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  languageSetting: "auto",
  lang: "en",
  speechLocale: "en-IN",
  isRtl: false,
  t: (key) => TRANSLATION_KEYS[key],
});

export const LanguageProvider: React.FC<{
  languageSetting: string;
  children: React.ReactNode;
}> = ({ languageSetting, children }) => {
  const value = useMemo<LanguageContextValue>(() => {
    const resolved = resolveLanguageCode(languageSetting);
    const meta = SUPPORTED_LANGUAGES.find((l) => l.code === resolved);
    const speechLocale = meta?.speechLocale || "en-IN";
    const isRtl = Boolean(meta?.rtl);
    return {
      languageSetting,
      lang: resolved,
      speechLocale,
      isRtl,
      t: (key: TranslationKey) => translateKey(resolved, key),
    };
  }, [languageSetting]);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = value.lang === "hinglish" ? "hi-Latn" : value.lang;
      document.documentElement.dir = value.isRtl ? "rtl" : "ltr";
    }
  }, [value.lang, value.isRtl]);

  return React.createElement(LanguageContext.Provider, { value }, children);
};

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
